-- Q27
-- Rank products by total revenue.
-- You must first calculate product-level revenue from order_items, then use a window function to rank products.
-- Return:
-- - product_id
-- - total_revenue
-- - revenue_rank
-- Highest revenue = rank 1.
WITH PRO_REV AS(
SELECT PRODUCT_ID,SUM(PRICE_USD)AS PRODUCT_REV
FROM ORDER_ITEMS
GROUP BY PRODUCT_ID
)
SELECT *,RANK() OVER(ORDER BY PRODUCT_REV DESC)AS REV_RANK
FROM PRO_REV;
-- Q28
-- Rank products within each revenue category.
-- First calculate product revenue and classify:
-- < 500       → Low
-- 500–1000    → Medium
-- > 1000      → High

-- Then rank products within each category by revenue descending.
-- Return:
-- - product_id
-- - total_revenue
-- - revenue_category
-- - category_rank
WITH REV_CAT AS(
SELECT PRODUCT_ID,SUM(PRICE_USD) AS TOTAL_REV,
	CASE
		WHEN SUM(PRICE_USD)<500 THEN 'LOW'
		WHEN SUM(PRICE_USD) BETWEEN 500 AND 1000 THEN 'MEDIUM'
		ELSE 'HIGH'
	END AS REVENUE_CAT
FROM ORDER_ITEMS
GROUP BY PRODUCT_ID
)
SELECT *,RANK() OVER(PARTITION BY REVENUE_CAT ORDER BY TOTAL_REV DESC )AS CATEGORY_RANK
FROM REV_CAT;
-- Q29
-- For every customer, display their orders and classify each order as:
-- First Order
-- Second Order
-- Third+ Order

-- based on the customer's chronological order history.
-- Return:
-- - user_id
-- - order_id
-- - created_at
-- - order_sequence
-- - order_stage
WITH customer_orders AS (
    SELECT
        user_id,
        order_id,
        created_at,
        ROW_NUMBER() OVER (
            PARTITION BY user_id
            ORDER BY created_at
        ) AS order_sequence
    FROM orders
)
SELECT
    user_id,
    order_id,
    created_at,
    order_sequence,
    CASE
        WHEN order_sequence = 1 THEN 'First Order'
        WHEN order_sequence = 2 THEN 'Second Order'
        ELSE 'Third+ Order'
    END AS order_stage
FROM customer_orders;
