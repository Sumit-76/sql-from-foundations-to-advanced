-- - revenue_percentage
-- Requirements:
-- customer_total_orders
-- Number of orders placed by that customer.
-- customer_total_revenue
-- Total revenue generated by that customer.
-- customer_avg_order_price
-- Average order price of that customer.
-- order_number
-- Chronological order number:
-- oldest → 1
-- next   → 2
-- next   → 3
-- ...

-- price_rank_within_customer
-- Rank each customer's orders by price:
-- highest price → rank 1

-- revenue_percentage
-- Each order's contribution to the customer's total revenue.
-- Sort the final result by:
-- user_id
-- created_at

WITH CUS_LEV AS(

SELECT USER_ID,ORDER_ID,CREATED_AT,PRICE_USD,
	COUNT(*) OVER(PARTITION BY USER_ID)AS CUSTOMER_TOTAL_ORDER,
	SUM(PRICE_USD) OVER(PARTITION BY USER_ID)AS CUSTOMER_TOTAL_REVENUE,
	AVG(PRICE_USD) OVER(PARTITION BY USER_ID)AS CUSTOMER_AVG_ORDER_PRICE,
	ROW_NUMBER() OVER(PARTITION BY USER_ID ORDER BY CREATED_AT)AS ORDER_NUMBER,
	RANK() OVER(PARTITION BY USER_ID ORDER BY PRICE_USD DESC)AS PRICE_RANK_WITHIN_CUS
FROM ORDERS
)
SELECT *,PRICE_USD/CUSTOMER_TOTAL_REVENUE * 100 AS REV_PERCENTAGE
FROM CUS_LEV
ORDER BY USER_ID,CREATED_AT;