-- Topic 2 -- Aggregate Functions

-- 🟢 EASY
-- Q1 Find the total number of records in the orders table.
SELECT COUNT(*) AS no_of_records
FROM orders; 
-- Q2 Find the total number of records in the products table.
SELECT COUNT(*) AS no_of_records
FROM products; 
-- Q3 Find the total revenue represented by price_usd in the orders table.
SELECT SUM(price_usd)AS total_revenue
FROM orders;
-- Q4 Find the total COGS represented by cogs_usd in the orders table.
SELECT SUM(cogs_usd)AS total_cogs
FROM orders;
-- Q5 Find the average order price.
SELECT AVG(price_usd)AS avg_order_price
FROM orders;
-- Q6 Find the highest order price.
SELECT MAX(price_usd)AS highest_order_price
FROM orders;
-- Q7 Find the lowest order price.
SELECT MIN(price_usd)AS lowest_order_price
FROM orders;
-- Q8 Find the average number of items purchased per order.
SELECT AVG(items_purchased)AS avg_items_purchased
FROM orders;
-- Q9 Find the total number of items purchased across all orders.
SELECT SUM(items_purchased)AS total_items_purchased
FROM orders;
-- Q10 Find the highest number of items purchased in a single order.
SELECT MAX(items_purchased)AS highest_no_of_items_purchased
FROM orders;
-- 🟡 MEDIUM

-- Q11 For the orders table, find: total orders, total revenue, average order price, highest order price, lowest order price
-- Return everything in one result row.
SELECT COUNT(*) AS total_order,
	   SUM(price_usd) AS total_revenue,
	   AVG(price_usd) AS avg_order_price,
	   MAX(price_usd) AS highest_order_pr,
	   MIN(price_usd) AS lowest_order_pr
FROM orders;
-- Q12 Find the total revenue and total COGS from all orders.
SELECT SUM(price_usd) AS total_revenue,SUM(cogs_usd) AS total_cogs
FROM orders ;
-- Q13 Find the difference between total revenue and total COGS.
SELECT SUM(price_usd) - SUM(cogs_usd) AS profit
FROM orders;
-- Q14 Find the average revenue generated per order.
SELECT AVG(price_usd)AS avg_rev
FROM orders;
-- Q15 Find the average COGS per order.
SELECT AVG(cogs_usd)AS avg_cogs
FROM orders;
-- Q16 Find the difference between the highest and lowest order price.
SELECT MAX(price_usd) - MIN(price_usd) AS diff
FROM orders;
-- Q17 Find the total number of orders where items_purchased = 2.
SELECT COUNT(*)AS total_number_of_orders
FROM orders
WHERE items_purchased = 2;
-- Q18 Find how many orders have a price greater than 100.
SELECT COUNT(*)AS no_of_orders
FROM orders
WHERE price_usd > 100 ;
-- Q19 Find how many orders have a price less than 50.
SELECT COUNT(*)AS no_of_orders
FROM orders
WHERE price_usd < 50 ;
-- Q20 Find the average order price for orders where the price is greater than 100.
SELECT AVG(price_usd)AS avg_order_price 
FROM orders
WHERE price_usd > 100 ;

-- 🔴 HARD
-- Q21 Find the number of unique customers who have placed an order.
SELECT COUNT(DISTINCT user_id)AS unique_customer
FROM orders;
-- Q22 Find the number of unique website sessions that resulted in an order.
SELECT COUNT(DISTINCT website_session_id) AS sessions_with_orders
FROM orders;
-- Q23 Find the total revenue generated by orders containing 2 items.
SELECT SUM(price_usd)AS total_revenue
FROM orders
WHERE items_purchased = 2;
-- Q24 Find the average order price for orders containing 2 items.
SELECT AVG(price_usd)AS average_order_price
FROM orders
WHERE items_purchased = 2;
-- Q25 Find the total revenue from orders where COGS is greater than 50.
SELECT SUM(price_usd)AS total_revenue
FROM orders
WHERE cogs_usd > 50;
-- Q26 Find the average profit per order, where: Profit = price_usd - cogs_usd
SELECT AVG(price_usd - cogs_usd)AS avg_profit
FROM orders;
-- Q27 Find the highest profit generated by a single order.
SELECT MAX(price_usd - cogs_usd)AS highest_profit
FROM orders;
-- Q28 Find the lowest profit generated by a single order.
SELECT MIN(price_usd - cogs_usd)AS lowest_profit
FROM orders;
-- Q29 Find the total profit across all orders.
SELECT SUM(price_usd - cogs_usd)AS total_profit
FROM orders;
-- Q30 Find all of these in one result row:
-- - total number of orders
-- - unique customers
-- - total revenue
-- - total COGS
-- - total profit
-- - average order price
-- - highest order price
-- - lowest order price
-- - average items purchased
SELECT COUNT(*)AS total_order,
		COUNT(DISTINCT user_id)AS unique_customer,
		SUM(price_usd)AS total_revenue,
		SUM(cogs_usd)AS total_cogs,
		SUM(price_usd-cogs_usd)AS total_profit,
		AVG(price_usd)AS avg_price,
		MAX(price_usd)AS maximum_price,
		MIN(price_usd)AS minimum_price,
		AVG(ITEMS_PURCHASED)AS avg_items_purchased
FROM ORDERS;