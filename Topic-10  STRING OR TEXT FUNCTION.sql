-- Q27
-- Create a cleaned source from:
-- utm_source

-- using:
-- TRIM + LOWER

-- Then calculate:
-- - cleaned source
-- - total sessions
-- - unique users
-- - total orders
SELECT
    LOWER(TRIM(ws.utm_source)) AS cleaned_utm,
    COUNT(DISTINCT ws.website_session_id) AS total_sessions,
    COUNT(DISTINCT ws.user_id) AS unique_users,
    COUNT(DISTINCT o.order_id) AS total_orders
FROM website_sessions ws
LEFT JOIN orders o
    ON ws.website_session_id = o.website_session_id
GROUP BY LOWER(TRIM(ws.utm_source));
-- Q28
-- Create a session classification:
-- Google + mobile → Google Mobile
-- Google + desktop → Google Desktop
-- Facebook + mobile → Facebook Mobile
-- Facebook + desktop → Facebook Desktop
-- Everything else → Other

-- Then count sessions in each category.
SELECT
    CASE
        WHEN TRIM(utm_source) ILIKE '%google%'
             AND TRIM(device_type) ILIKE '%mobile%'
            THEN 'Google Mobile'

        WHEN TRIM(utm_source) ILIKE '%google%'
             AND TRIM(device_type) ILIKE '%desktop%'
            THEN 'Google Desktop'

        WHEN TRIM(utm_source) ILIKE '%facebook%'
             AND TRIM(device_type) ILIKE '%mobile%'
            THEN 'Facebook Mobile'

        WHEN TRIM(utm_source) ILIKE '%facebook%'
             AND TRIM(device_type) ILIKE '%desktop%'
            THEN 'Facebook Desktop'
        ELSE 'Other'
    END AS session_category,
    COUNT(*) AS total_sessions
FROM website_sessions
GROUP BY
    CASE
        WHEN TRIM(utm_source) ILIKE '%google%'
             AND TRIM(device_type) ILIKE '%mobile%'
            THEN 'Google Mobile'
        WHEN TRIM(utm_source) ILIKE '%google%'
             AND TRIM(device_type) ILIKE '%desktop%'
            THEN 'Google Desktop'
        WHEN TRIM(utm_source) ILIKE '%facebook%'
             AND TRIM(device_type) ILIKE '%mobile%'
            THEN 'Facebook Mobile'
        WHEN TRIM(utm_source) ILIKE '%facebook%'
             AND TRIM(device_type) ILIKE '%desktop%'
            THEN 'Facebook Desktop'
        ELSE 'Other'
    END;
-- Q29
-- Find the top 5 product names with the greatest number of characters.
-- Return:
-- - product_name
-- - name_length
-- Sort longest first.
WITH PRO_LEV AS(
SELECT PRODUCT_NAME,LENGTH(PRODUCT_NAME)AS NAME_LEN,ROW_NUMBER() OVER(ORDER BY LENGTH(PRODUCT_NAME) DESC)AS RN
FROM PRODUCTS
)
SELECT PRODUCT_NAME,NAME_LEN
FROM PRO_LEV
WHERE RN <=5
ORDER BY NAME_LEN DESC;
