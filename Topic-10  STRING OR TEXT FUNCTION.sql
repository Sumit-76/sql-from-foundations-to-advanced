-- Q30 — Analyst Level
-- Create a cleaned marketing-source analysis containing:
-- - cleaned utm_source
-- - total sessions
-- - unique users
-- - total orders
-- - total revenue
-- Cleaning rule:
-- LOWER(TRIM(utm_source))

-- Include sources that have sessions but no orders.
-- Sort by total revenue descending.
SELECT
    LOWER(TRIM(ws.utm_source)) AS cleaned_utm_source,
    COUNT(DISTINCT ws.website_session_id) AS total_sessions,
    COUNT(DISTINCT ws.user_id) AS unique_users,
    COUNT(DISTINCT o.order_id) AS total_orders,
    SUM(o.price_usd) AS total_revenue
FROM website_sessions ws
LEFT JOIN orders o
    ON ws.website_session_id = o.website_session_id
GROUP BY LOWER(TRIM(ws.utm_source))
ORDER BY total_revenue DESC NULLS LAST;